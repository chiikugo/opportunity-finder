/* ==========================================================================
   opportunities.js — the hand-picked list of fellowships, residencies,
   grants, internships, part-time gigs and volunteer roles.
   --------------------------------------------------------------------------
   WHAT THIS FILE IS
   A plain list (an "array") of opportunity objects. The app reads this list,
   scores every item against your resume / prompt, filters it, and shows it
   as cards on the "Fellowships & programs" tab. Nothing here talks to the
   internet — it is just data, so it's the safest file to edit.

   WHEN WAS IT CHECKED?
   Every entry was researched on LAST_CHECKED below. Deadlines move every
   year, so each card links to the official page — always confirm there.

   HOW TO ADD AN OPPORTUNITY
   Copy any { ... } block, paste it at the end of the list, and change the
   values. Field guide:

     id          unique short name, letters/dashes only (used to save it)
     title       name of the program
     org         who runs it
     url         the official page (people click this)
     kind        "fellowship" | "residency" | "grant" | "internship"
                 | "part-time" | "volunteer"
     fields      any of "tech", "art", "fashion", "research"
     pay         "paid" (wage/salary) | "stipend" (fixed award/stipend)
                 | "unpaid"
     payNote     the money in words, e.g. "$10,000 stipend"
     where       "remote" | "hybrid" | "onsite"
     whereNote   details, e.g. "On-site in New York"
     eligibility short note on who can apply
     deadline    "YYYY-MM-DD" if a deadline is known & upcoming, else null
     opens       "YYYY-MM-DD" if we know roughly when it opens, else null
     rolling     true if you can apply any time
     cycle       plain-English timing note (shown on the card)
     blurb       one or two sentences on what it is
     tags        keywords the matcher looks for in your resume / prompt
                 (lower-case; more specific = better matches)
     check       HOW the daily scraper confirms it's open right now.
                 A program is only shown on the site on days its check
                 passes — closed, "next round" or unverifiable = hidden.
                   { type: "greenhouse", board, title }  → open while a job
                       whose title matches is posted on that Greenhouse board
                       (the card then links straight to those postings)
                   { type: "page", url?, open, closed }  → open when the page
                       matches `open` and NOT `closed` (and any date right
                       after the open wording hasn't passed)
                   { type: "deadline", url?, confirm }   → open until
                       `deadline`, while the page still mentions `confirm`
                   { type: "rolling" }  → always-open sign-up; open while
                       the page loads
                   null  → can't be checked automatically, so never shown
   ========================================================================== */

